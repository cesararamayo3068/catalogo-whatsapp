CREATE TABLE category (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL UNIQUE, active BOOLEAN NOT NULL DEFAULT TRUE, sort_order INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE product (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 sku VARCHAR(100), name VARCHAR(180) NOT NULL, description VARCHAR(6000) NOT NULL,
 category_id BIGINT NOT NULL REFERENCES category(id), price NUMERIC(19,2) NOT NULL CHECK(price >= 0),
 promotional_price NUMERIC(19,2) CHECK(promotional_price >= 0 AND promotional_price < price),
 active BOOLEAN NOT NULL, available BOOLEAN NOT NULL, featured BOOLEAN NOT NULL,
 minimum_quantity INTEGER NOT NULL CHECK(minimum_quantity BETWEEN 1 AND 9999),
 created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
 version BIGINT NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX product_sku_unique ON product(sku) WHERE sku IS NOT NULL;
CREATE INDEX product_category_idx ON product(category_id);
CREATE INDEX product_public_idx ON product(active, featured);
CREATE INDEX product_name_idx ON product(lower(name));
CREATE TABLE product_image (product_id BIGINT NOT NULL REFERENCES product(id) ON DELETE CASCADE, position INTEGER NOT NULL, url VARCHAR(500) NOT NULL, PRIMARY KEY(product_id,position));
CREATE TABLE product_attribute (product_id BIGINT NOT NULL REFERENCES product(id) ON DELETE CASCADE, attribute_name VARCHAR(80) NOT NULL, attribute_value VARCHAR(200) NOT NULL, PRIMARY KEY(product_id,attribute_name));
CREATE TABLE product_variant (
 id UUID PRIMARY KEY, product_id BIGINT NOT NULL REFERENCES product(id) ON DELETE CASCADE,
 label VARCHAR(160) NOT NULL, sku VARCHAR(100), price NUMERIC(19,2) CHECK(price >= 0), available BOOLEAN NOT NULL,
 CONSTRAINT variant_label_unique UNIQUE(product_id,label)
);
CREATE INDEX variant_product_idx ON product_variant(product_id);
CREATE TABLE variant_attribute (variant_id UUID NOT NULL REFERENCES product_variant(id) ON DELETE CASCADE, attribute_name VARCHAR(80) NOT NULL, attribute_value VARCHAR(200) NOT NULL, PRIMARY KEY(variant_id,attribute_name));
CREATE TABLE admin_user (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, username VARCHAR(100) NOT NULL UNIQUE, password_hash VARCHAR(100) NOT NULL, enabled BOOLEAN NOT NULL DEFAULT TRUE);
